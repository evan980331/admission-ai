export type AcquisitionTaskStatus =
  | "PENDING"
  | "CAPTURED"
  | "PARSED"
  | "LOADED"
  | "FAILED"
  | "TRAFFIC_LIMITED"
  | "NO_TARGET_PAGE";

export interface AcquisitionTask {
  academicYear: number;
  schoolCode: string;
  departmentCode: string;
  departmentName: string | null;
  source: "official-pdf";
  url: string;
  status: AcquisitionTaskStatus;
}

export function assertPdfOrder(codes: string[]): void {
  if (codes.length === 0) throw new Error("PDF order list is empty");
  if (new Set(codes).size !== codes.length) throw new Error("duplicate codes in PDF order list");
  for (const c of codes) {
    if (!/^\d{6}$/.test(c)) throw new Error(`non-6-digit code in PDF order list: ${c}`);
  }
}

/** Build a PENDING task for one PDF-backed department (candidate URL only). */
export function buildAcquisitionTask(args: {
  academicYear: number;
  departmentCode: string;
  departmentName?: string | null;
}): AcquisitionTask {
  if (!/^\d{6}$/.test(args.departmentCode)) throw new Error(`departmentCode must be 6 digits`);
  if (!Number.isInteger(args.academicYear) || args.academicYear < 100 || args.academicYear > 130) {
    throw new Error(`academicYear must be 100-130`);
  }
  return {
    academicYear: args.academicYear,
    schoolCode: args.departmentCode.slice(0, 3),
    departmentCode: args.departmentCode,
    departmentName: args.departmentName ?? null,
    source: "official-pdf",
    url: buildOfficialDetailUrl(args.academicYear, args.departmentCode),
    status: "PENDING",
  };
}

/** First PDF code (in PDF order) with no raw detail yet. */
export function firstPending(pdfOrder: string[], rawCodes: Set<string>): string | null {
  for (const code of pdfOrder) {
    if (!rawCodes.has(code)) return code;
  }
  return null;
}

/**
 * Mechanical link extraction from an official school PDF (raw latin1 text).
 * Each "詳細資料" row carries link annot(s) with the REAL desktop detail URL;
 * codes come out in document (PDF) order, deduped. No CMap decoding needed
 * because annot URIs are stored uncompressed. Pure string function.
 */
export interface PdfDetailLink {
  code: string;
  url: string;
}

export function extractPdfDetailLinks(pdfText: string): PdfDetailLink[] {
  const out: PdfDetailLink[] = [];
  const seen = new Set<string>();
  for (const m of pdfText.matchAll(/\/URI\s*\((https:\/\/www\.cac\.edu\.tw\/[^)]*?\/115_(\d{6})\.htm[^)]*)\)/g)) {
    const code = m[2]!;
    if (seen.has(code)) continue;
    seen.add(code);
    out.push({ code, url: m[1]! });
  }
  return out;
}

