export type QueueStatus =
  | "PENDING"
  | "CAPTURED"
  | "STORED"
  | "PARSED"
  | "VALIDATED"
  | "LOAD_REQUIRED"
  | "LOADED"
  | "FAILED"
  | "TRAFFIC_LIMITED"
  | "NO_TARGET_PAGE";

export interface InventoryEntry {
  academicYear: number;
  schoolCode: string;
  departmentCode: string;
  departmentName: string | null;
  detailUrl: string;
  source: "official-pdf";
}

/** Build the 64-school inventory from mechanical PDF link extraction. */
export function buildInventory(pdfTexts: Record<string, string>): InventoryEntry[] {
  const entries: InventoryEntry[] = [];
  for (const [schoolCode, text] of Object.entries(pdfTexts)) {
    for (const link of extractPdfDetailLinks(text)) {
      if (!link.code.startsWith(schoolCode)) {
        throw new Error(`PDF ${schoolCode}: code ${link.code} does not belong to school ${schoolCode}`);
      }
      entries.push({
        academicYear: 115,
        schoolCode,
        departmentCode: link.code,
        departmentName: PDF_NAMES[link.code] ?? null,
        detailUrl: link.url,
        source: "official-pdf",
      });
    }
  }
  return entries;
}

/**
 * Resolve one entry's status. Priority: DB canonical > raw capture > inventory.
 * dbLoaded=null means DB unchecked (env-gated) — never guessed LOADED; the
 * legacy file-only states (CAPTURED/STORED/PARSED/VALIDATED) are kept for
 * offline display. dbLoaded=false means DB was checked and the row is
 * missing: raw-present entries collapse to LOAD_REQUIRED (retryable DB load
 * from existing raw, no re-capture) instead of looking "done".
 */
export function resolveStatus(
  entry: InventoryEntry,
  state: { dbLoaded: boolean | null; rawHtm: boolean; rawMeta: boolean; parsed: boolean | null; validated: boolean | null },
): QueueStatus {
  if (state.dbLoaded === true) return "LOADED";
  if (state.dbLoaded === false) {
    if (!state.rawHtm) return "PENDING";
    if (state.parsed === false) return "FAILED";
    if (state.validated === false) return "FAILED";
    return "LOAD_REQUIRED";
  }
  if (!state.rawHtm) return "PENDING";
  if (!state.rawMeta) return "CAPTURED";
  if (state.parsed === false) return "FAILED";
  if (state.validated === false) return "FAILED";
  if (state.validated === true) return "VALIDATED";
  if (state.parsed === true) return "PARSED";
  return "STORED";
}

/**
 * Work selector for acquisition runners. LOADED is always skipped; FAILED
 * needs human attention (never auto-retried); every other non-terminal file
 * state is actionable. In particular LOAD_REQUIRED (raw exists, DB missing)
 * must be picked up — selecting PENDING only strands raw-complete entries
 * forever (003112/003192 precedent).
 */
export function isActionableStatus(status: QueueStatus): boolean {
  return status === "PENDING" || status === "LOAD_REQUIRED";
}
